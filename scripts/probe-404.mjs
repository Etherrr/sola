import { chromium } from '@playwright/test';
const b = await chromium.launch();
const page = await b.newPage();
page.on('response', (r) => { if (r.status() >= 400) console.log('BAD', r.status(), r.url()); });
page.on('requestfailed', (r) => console.log('FAILED', r.url(), r.failure()?.errorText));
await page.goto('http://127.0.0.1:3000/track/');
await page.getByRole('button', { name: 'Mixed tokens' }).click();
await page.getByRole('heading', { name: 'Result' }).waitFor();
await page.waitForTimeout(500);
await b.close();
console.log('probe done');
