import {test,expect} from '@playwright/test';
const session={status:'ok',email:'user@example.test',fresh:true};
test('native sign-in and optional import stay one account app',async({page},info)=>{
 let preview=0,discovery=0;
 await page.route('**/api/v1/**',r=>r.fulfill({status:401,contentType:'application/json',body:'{"error":"auth_required"}'}));
 await page.route('**/api/v1/auth/email/session',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(session)}));
 await page.route('**/api/v1/portfolio/addresses',r=>r.fulfill({status:200,contentType:'application/json',body:'{"status":"ok","addresses":[]}'}));
 await page.route('**/api/v1/claim/features',r=>{discovery++;return r.fulfill({status:200,contentType:'application/json',body:'{"claim":true}'});});
 await page.route('**/api/v1/claim/preview',r=>{preview++;return r.fulfill({status:503,contentType:'application/json',body:'{"error":{"code":"disabled"}}'});});
 await page.goto('/sign-in/');
 await expect(page.locator('body')).not.toContainText('Legacy Track');
 await expect(page.getByRole('link',{name:'Legacy Track list'})).toHaveCount(0);
 await page.screenshot({path:`/downloads/coherent-signin-${info.project.name}.png`,fullPage:false});
 await page.goto('/account/');
 await expect(page.getByText('Import saved addresses',{exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Verify previous sign-in'})).not.toBeVisible();
 expect(preview).toBe(0);expect(discovery).toBe(1);
 await page.getByText('Import saved addresses',{exact:true}).scrollIntoViewIfNeeded();
 await page.screenshot({path:`/downloads/coherent-import-collapsed-${info.project.name}.png`,fullPage:false});
 await page.getByText('Import saved addresses',{exact:true}).focus();await page.keyboard.press('Enter');
 await expect(page.getByRole('link',{name:'Verify previous sign-in'})).toBeVisible();
 expect(preview).toBe(0);
 await page.getByRole('link',{name:'Verify previous sign-in'}).scrollIntoViewIfNeeded();
 await page.screenshot({path:`/downloads/coherent-import-${info.project.name}.png`,fullPage:false});
 await page.getByRole('link',{name:'Verify previous sign-in'}).click();
 await expect(page).toHaveURL(/\/account\/legacy-bridge\/$/);
 expect(preview).toBe(0);
 await page.getByRole('button',{name:'Check for saved addresses'}).click();
 await expect(page.getByText('Could not check your old saved addresses.',{exact:false})).toBeVisible();expect(preview).toBe(1);
 await page.goto('/portfolio/');
 await expect(page.getByRole('heading',{name:'Saved addresses',exact:true})).toBeVisible();
 await expect(page.locator('body')).not.toContainText('Legacy Track');
 await expect(page.locator('a[href="/demo"]')).toHaveCount(0);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
